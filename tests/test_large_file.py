"""Large synthetic file tests: wide-format USUBR/FUNC (nsyms > 256).

The compiler emits 3-byte short USUBR/FUNC only when ``nsyms <= 256``; larger
symbol tables use 5/6-byte wide encodings (``35 <argc> <idx16> <flags=3>`` /
``51 <argc> <idx16> <flags=1> 00``). This path was previously covered only by
``tests/atlisp_u.lsp`` (@lisp 综合包), whose tests skip when the fixture is
absent. The deterministic synthetic fixture ``tests/large_synthetic.lsp``
(generated by ``scripts/gen_large_fixture.py``) provides self-contained
coverage of the wide-format compile / disasm->asm roundtrip / decompile
recovery.

- 120 cross-referencing functions (``lgf-000`` … ``lgf-119``), each with two
  args, two /locals, and a branch that calls neighbours (``lgf-119`` / ``lgf-001``)
- 6 variadic functions (``lgf-var-*`` with ``&optional`` / ``&rest``)
- 4 commands (``c:lgf-cmd-000/030/060/090``) that call a regular function, so
  the decompiler's dead-code filter keeps the reachable chain
- 12 top-level ``setq`` (mixed mode → seg1 module code) + a final ``princ``
"""
import os
import re
import sys
import tempfile

import pytest

sys.path.insert(0, '.')

from asm.assembler import assemble_lasm, disassemble_fas
from compiler.cli import cmd_compile
from decompiler.fas4_decompiler import (
    ControlFlowAnalyzer,
    Disassembler,
    Fas4Decompiler,
    Fas4Parser,
    extract_stub_function_names,
    is_compact_stub,
    use_short_subr,
)
from tools.validate import parse_tokens, tokenize, validate_ast

FIXTURE = os.path.join("tests", "large_synthetic.lsp")


def _validate(source: str) -> tuple:
    tokens, errs = tokenize(source)
    if errs:
        return False, errs
    forms, errs = parse_tokens(tokens)
    if errs:
        return False, errs
    errs = validate_ast(forms)
    return (False, errs) if errs else (True, [])


def _tmp(name: str) -> str:
    return os.path.join(tempfile.gettempdir(), name)


def _seg0(path: str) -> bytes:
    return Fas4Parser().parse(path).bytecode


def test_large_fixture_exists():
    """Fixture must be committed (not a skip-on-missing atlisp_u dependency)."""
    assert os.path.exists(FIXTURE), "tests/large_synthetic.lsp missing"


def test_large_compile_wide_format():
    """Compile triggers wide-format USUBR/FUNC: nsyms > 256, 5/6-byte encodings.

    Wide 5-byte USUBR bytes: ``35 <argc> <idx16-le> 03``; wide 6-byte FUNC:
    ``51 <argc> <idx16-le> 01 00``. Short 3-byte forms use ``35 <argc> <idx8>``
    and ``51 <argc> <idx8>`` respectively (flags omitted).
    """
    out = _tmp("large_synth.fas")
    try:
        result = cmd_compile(FIXTURE, out)
        assert os.path.exists(result)
        fas = Fas4Parser().parse(result)
        assert fas.nsyms > 256, f"expected wide-format nsyms>256, got {fas.nsyms}"
        assert len(fas.bytecode) > 0

        # 宽格式 USUBR（5 字节：35 <argc> <idx16> 03）与 FUNC（6 字节：51 <argc> <idx16> 01 00）
        assert re.search(rb"\x35.{3}\x03", fas.bytecode), "no wide USUBR (35 ... 03)"
        assert re.search(rb"\x51.{3}\x01\x00", fas.bytecode), "no wide FUNC (51 ... 01 00)"
    finally:
        if os.path.exists(out):
            os.unlink(out)


def test_large_compile_verify_clean():
    """cmd_compile's internal verify_fas must find no fatal issues.

    verify_fas blocks writing on fatal problems (UNK misparse / out-of-range
    symbol refs / stream damage) that would 0xC0000005 in CAD. Compilation
    exiting with a file present already proves this; assert the file parses
    back and the two segments are non-trivial.
    """
    out = _tmp("large_synth_v.fas")
    try:
        result = cmd_compile(FIXTURE, out)
        assert os.path.exists(result)
        fas = Fas4Parser().parse(result)
        assert len(fas.bytecode) > 0
        assert fas.nsyms > 0
    finally:
        if os.path.exists(out):
            os.unlink(out)


def test_large_disasm_asm_roundtrip():
    """disasm -> asm roundtrip keeps seg0 + nsyms byte-identical (wide format)."""
    out = _tmp("large_synth.fas")
    rt = _tmp("large_synth_rt.fas")
    try:
        cmd_compile(FIXTURE, out)
        lasm_text = disassemble_fas(out)
        assert ".format compact" in lasm_text
        # 宽格式 USUBR 在 .lasm 中带第 3 个 flags 操作数
        assert re.search(r"USUBR \d+, [^,]+,\s*\d+", lasm_text), "no wide USUBR in lasm"
        assemble_lasm(lasm_text, rt)
        assert _seg0(out) == _seg0(rt)
        o = Fas4Parser().parse(out)
        n = Fas4Parser().parse(rt)
        assert o.nsyms == n.nsyms
    finally:
        for p in (out, rt):
            if os.path.exists(p):
                os.unlink(p)


def test_large_decompile_recovers_functions():
    """Decompile recovers the reachable function set and the output validates.

    Commands call regular functions, so the dead-code filter
    (``_filter_runnable_specs``) keeps ``lgf-000``, its branches
    (``lgf-001``/``lgf-119``), and the transitive chain. Assert the full
    120-function source set is recovered (plus the 4 commands) and the
    decompiled Lisp re-validates. Variadic ``lgf-var-*`` are unreferenced by
    commands/init and correctly pruned here — their full recovery is asserted
    in ``test_large_control_flow_full_recovery``.
    """
    out = _tmp("large_synth.fas")
    lsp = _tmp("large_synth_decomp.lsp")
    try:
        cmd_compile(FIXTURE, out)
        Fas4Decompiler().decompile(out, lsp)
        code = open(lsp, encoding="utf-8").read()
        defuns = re.findall(r"\(defun\s+(\S+)", code)
        assert len(defuns) >= 124, f"expected ~124 defuns, got {len(defuns)}"
        names = set(defuns)
        assert "lgf-000" in names and "lgf-119" in names
        assert "c:lgf-cmd-000" in names
        ok, errs = _validate(code)
        assert ok, f"Validation failed: {errs}"
    finally:
        for p in (out, lsp):
            if os.path.exists(p):
                os.unlink(p)


def test_large_control_flow_full_recovery():
    """Raw control-flow analysis finds all DEFUN bodies (130, incl. variadic).

    Independent of the dead-code filter: ``find_functions`` splits seg0 at
    DEFUN headers and must locate every stub function.
    """
    out = _tmp("large_synth.fas")
    try:
        cmd_compile(FIXTURE, out)
        fas = Fas4Parser().parse(out)
        stub = is_compact_stub(fas.bytecode, fas.function_catalog, len(fas.symbol_slots))
        dis = Disassembler(
            short_subr=use_short_subr(fas.bytecode, fas.nsyms, fas.function_catalog, len(fas.symbol_slots))
        )
        insts = dis.disassemble(fas.bytecode, fas.nsyms, sym_count=len(fas.symbol_slots) if stub else None)
        cf = ControlFlowAnalyzer(insts, fas.function_catalog, function_names=extract_stub_function_names(fas))
        funcs = cf.find_functions()
        assert len(funcs) >= 130, f"expected >=130 functions, got {len(funcs)}"
    finally:
        if os.path.exists(out):
            os.unlink(out)


@pytest.mark.parametrize("opt", [0, 1, 2, 3])
def test_large_roundtrip_opt_levels(opt):
    """Large file compiles + decompiles validly at every optimization level.

    -O1/O2/O3 transform the AST before codegen; the result must still be a
    loadable wide-format FAS whose decompile output re-validates.
    """
    out = _tmp(f"large_synth_O{opt}.fas")
    lsp = _tmp(f"large_synth_O{opt}_decomp.lsp")
    try:
        cmd_compile(FIXTURE, out, opt_level=opt)
        fas = Fas4Parser().parse(out)
        assert fas.nsyms > 256, f"-O{opt}: expected wide format, nsyms={fas.nsyms}"
        Fas4Decompiler().decompile(out, lsp)
        code = open(lsp, encoding="utf-8").read()
        assert "(defun lgf-000" in code, f"-O{opt}: lgf-000 lost from decompile"
        ok, errs = _validate(code)
        assert ok, f"-O{opt} validation failed: {errs}"
    finally:
        for p in (out, lsp):
            if os.path.exists(p):
                os.unlink(p)